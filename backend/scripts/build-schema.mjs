// Concatenates migrations/*.sql (in name order) into schema.sql. Run: node scripts/build-schema.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = ["-- GENERATED by scripts/build-schema.mjs from migrations/*.sql. Edit the migrations, not this file.\n"];
for (const f of files) out.push(`\n-- ===== ${f} =====\n` + readFileSync(join(dir, f), "utf8").trim() + "\n");
writeFileSync(join(root, "schema.sql"), out.join(""));
console.log("schema.sql built from", files.length, "migrations");
