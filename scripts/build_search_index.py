#!/usr/bin/env python3
"""Generate assets/search-data.js from the pages themselves. Usage: python3 scripts/build_search_index.py [--check]"""
import html, json, re, sys
from site_lib import *

CATS = [("tools/", "tools"), ("businesses/", "businesses"), ("cities/", "cities"), ("blog/", "blog"),
        ("google-business-profile/", "guides"), ("google-maps-seo/", "guides"), ("google-reviews/", "guides"),
        ("local-seo/", "guides"), ("business-growth/", "guides")]

def category(f):
    p = f[3:] if f.startswith("hi/") else f
    if p.endswith("index.html") and p.count("/") == 1:  # hub pages stay searchable under their category
        pass
    for pre, c in CATS:
        if p.startswith(pre):
            return c
    return None

def build():
    data = {"en": [], "hi": []}
    for f in html_files():
        s = read(f)
        if not indexable(f, s):
            continue
        c = category(f)
        if not c:
            continue
        t = re.sub(r"\s*\|\s*LocalBoost\s*$", "", html.unescape(title(s)))
        data["hi" if f.startswith("hi/") else "en"].append(
            {"title": t, "url": "/" + re.sub(r"index\.html$", "", f), "cat": c, "desc": html.unescape(description(s))})
    return "// GENERATED by scripts/build_search_index.py. Do not edit.\nwindow.LB_SEARCH_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", {k: len(v) for k, v in data.items()}

if __name__ == "__main__":
    js, n = build()
    if "--check" in sys.argv:
        ok = read("assets/search-data.js") == js
        print("search index up to date" if ok else "assets/search-data.js is stale: run python3 scripts/build_search_index.py")
        sys.exit(0 if ok else 1)
    open(ROOT + "/assets/search-data.js", "w", encoding="utf-8").write(js)
    print("search index:", n)
